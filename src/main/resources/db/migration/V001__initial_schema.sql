CREATE INDEX idx_pets_species ON pets (species);
CREATE INDEX idx_pets_status ON pets (status);
CREATE INDEX idx_businesses_type ON businesses (type);
CREATE INDEX idx_pets_municipality ON pets (municipality_id);
CREATE INDEX idx_businesses_municipality ON businesses (municipality_id);
CREATE INDEX idx_reviews_business ON reviews (business_id);
CREATE INDEX idx_bookings_biz_time ON bookings (business_id, start_time);